// Build script: generates firebase-config.js from Netlify environment variables.
// Run automatically via netlify.toml build command.
// Set these variables in: Netlify Dashboard → Site Settings → Environment Variables

const fs = require('fs');

const required = [
    'FIREBASE_API_KEY',
    'FIREBASE_AUTH_DOMAIN',
    'FIREBASE_DATABASE_URL',
    'FIREBASE_PROJECT_ID',
    'FIREBASE_STORAGE_BUCKET',
    'FIREBASE_MESSAGING_SENDER_ID',
    'FIREBASE_APP_ID',
];

const missing = required.filter(key => !process.env[key]);
if (missing.length > 0) {
    console.error('❌ Missing required environment variables:', missing.join(', '));
    console.error('   Set them in Netlify Dashboard → Site Settings → Environment Variables');
    process.exit(1);
}

const config = `// Auto-generated by generate-firebase-config.js — do not edit manually.
const firebaseConfig = {
    apiKey: "${process.env.FIREBASE_API_KEY}",
    authDomain: "${process.env.FIREBASE_AUTH_DOMAIN}",
    databaseURL: "${process.env.FIREBASE_DATABASE_URL}",
    projectId: "${process.env.FIREBASE_PROJECT_ID}",
    storageBucket: "${process.env.FIREBASE_STORAGE_BUCKET}",
    messagingSenderId: "${process.env.FIREBASE_MESSAGING_SENDER_ID}",
    appId: "${process.env.FIREBASE_APP_ID}",
    measurementId: "${process.env.FIREBASE_MEASUREMENT_ID || ''}"
};

window.firebaseConfig = firebaseConfig;
`;

fs.writeFileSync('firebase-config.js', config);
console.log('✅ firebase-config.js generated from environment variables');
